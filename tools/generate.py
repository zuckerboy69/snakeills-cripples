"""Generate the Ren'Py mod from the design sheets.

  python3 tools/generate.py   ->  mod/snake_eater/sk_data.rpy, sk_chapter.rpy

Every row becomes one piece of code: characters/camos/mgs_assets rows become
entries in the data tables, each reaction row a reaction label, each codec row a
codec label and each scene row a scene label. Run tools/preflight.py first.
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "mod", "snake_eater")
MOODS = ("neutral", "shock", "happy", "angry")


def sheet(name):
    with open(os.path.join(ROOT, "design", name + ".json"), encoding="utf-8") as f:
        return json.load(f)


chars = {r["id"]: r for r in sheet("characters")["rows"]}
camos = sheet("camos")["rows"]
reactions = sheet("reactions")["rows"]
scenes = sheet("scenes")["rows"]
codec = sheet("codec")["rows"]
mgs = sheet("mgs_assets")

HEADER = "# GENERATED by tools/generate.py from design/*.json. Edit the sheets, not this file.\n\n"


def q(text):
    """A Ren'Py double-quoted string literal."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def say(who, text):
    """One say statement, using the character's KS speaker (or its signed variant)."""
    if who == "narr":
        return q(text)
    c = chars[who]
    if c["signed_var"] and text.startswith("[[ ") and text.endswith(" ]"):
        return "%s %s" % (c["signed_var"], q(text[3:-2]))
    return "%s %s" % (c["speaker_var"], q(text))


def line_ops(who, expr, text, ind):
    out = []
    if expr is not None and who != "narr":
        out.append('%s$ sk_expr("%s", "%s")' % (ind, who, expr))
    out.append(ind + say(who, text))
    return out


# ---------- data tables ----------
data = [HEADER, "init -2 python:\n"]
data.append("    SK_MOODS = %r\n" % (MOODS,))
data.append("    SK_CHARS = {\n")
for cid, c in chars.items():
    data.append("        %r: %r,\n" % (cid, {k: c[k] for k in ("kind", "speaker_var", "signed_var", "display_name", "color", "sprite_tag", "codename", "neutral", "shock", "happy", "angry", "repeat_line")}))
data.append("    }\n")
data.append("    SK_CAMO_ORDER = %r\n" % ([c["id"] for c in camos],))
data.append("    SK_CAMO_DEFAULT = %r\n" % ([c["id"] for c in camos if c["default"]][0],))
data.append("    SK_CAMOS = {\n")
for c in camos:
    data.append("        %r: %r,\n" % (c["id"], {"name": c["name"], "mgs_asset": c["mgs_asset"], "blurb": c["blurb"]}))
data.append("    }\n")
data.append("    SK_MGS = {\n")
for r in mgs["rows"]:
    data.append("        %r: %r,\n" % (r["key"], {"kind": r["kind"], "source_path": r["source_path"], "cache_file": r["cache_file"]}))
data.append("    }\n")
data.append("    SK_REACTORS = %r\n" % (sorted(set(r["who"] for r in reactions)),))
data.append("    SK_CODEC = {\n")
for c in codec:
    data.append("        %r: %r,\n" % (c["id"], {k: c[k] for k in ("contact", "freq", "ring_asset", "open_asset", "close_asset")}))
data.append("    }\n")

# ---------- labels ----------
lab = [HEADER]

lab.append("# Reactions: one label per (who, camo) row, run mid-line by sk_camo_picker.\n")
for r in reactions:
    lab.append("label sk_react_%s_%s:\n" % (r["who"], r["camo"]))
    for who, expr, text in r["lines"]:
        lab.extend(l + "\n" for l in line_ops(who, expr, text, "    "))
    lab.append("    return\n\n")

lab.append("# Codec calls: one label per codec row.\n")
for c in codec:
    lab.append("label sk_codec_%s:\n" % c["id"])
    lab.append('    $ sk_codec_open("%s")\n' % c["id"])
    for who, text in c["lines"]:
        lab.append("    " + say(who, text) + "\n")
    lab.append("    $ sk_codec_close()\n    return\n\n")

lab.append("# Scenes: one label per scene row.\n")
for s in scenes:
    lab.append("label sk_scene_%s:\n" % s["id"])
    lab.append('    $ sk_scene("%s", "%s", %r, %s)\n' % (s["bg"], s["music"], list(s["present"]), q(s["title"])))
    for op in s["ops"]:
        k = op[0]
        if k == "say":
            lab.extend(l + "\n" for l in line_ops(op[1], op[2], op[3], "    "))
        elif k == "n":
            lab.append("    " + q(op[1]) + "\n")
        elif k == "hint":
            lab.append("    " + q("{i}" + op[1] + "{/i}") + "\n")
        elif k == "show":
            lab.append('    $ sk_show("%s", "%s", "%s")\n' % (op[1], op[2], op[3]))
        elif k == "hide":
            lab.append('    $ sk_hide("%s")\n' % op[1])
        elif k == "present":
            lab.append("    $ sk_present = %r\n" % (list(op[1]),))
        elif k == "codec":
            lab.append("    call sk_codec_%s\n" % op[1])
        elif k == "sfx":
            lab.append('    $ sk_sfx("%s")\n' % op[1])
        elif k == "pause":
            lab.append("    $ renpy.pause(%s)\n" % float(op[1]))
        else:
            raise SystemExit("unknown op %r in %s" % (k, s["id"]))
    lab.append("    return\n\n")

lab.append("# The chapter, in scene order.\n")
lab.append("label snake_eater_chapter:\n")
for s in scenes:
    lab.append("    call sk_scene_%s\n" % s["id"])
lab.append("    return\n")

os.makedirs(OUT, exist_ok=True)
with open(os.path.join(OUT, "sk_data.rpy"), "w", encoding="utf-8", newline="\n") as f:
    f.write("".join(data))
with open(os.path.join(OUT, "sk_chapter.rpy"), "w", encoding="utf-8", newline="\n") as f:
    f.write("".join(lab))
print("generated %d reactions, %d codec calls, %d scenes" % (len(reactions), len(codec), len(scenes)))
